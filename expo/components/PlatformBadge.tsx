// Zooms the 24x24 artwork out around its centre.
function viewBoxFor(platform: Platform): string {
  const side = 24 / LOGO_SCALE[platform];
  const origin = 12 - side / 2;
  return `${origin} ${origin} ${side} ${side}`;
}

